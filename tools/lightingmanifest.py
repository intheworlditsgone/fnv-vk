"""Write replacements/lighting/replace.ini from the game's permutation table (tools/lightingtable.py output): every
shipped SLS pixel shader whose source file has a GLSL rewrite, with that variant's defines.

Packages= lists the shader packages whose build of every replaced shader they hold is the very bytecode of the verified
package (the table's): the game compiled its shader packages with different settings per hardware tier, so the rewrites
reproduce one tier's builds; other packages keep the translated originals.

FNV_SUN is added where the original takes the sun shadow term (sdp2spv's sun shadow pass: the manifest's sunLight), so
the replacement keeps the forward sun shadows (docs/SHADER_ABI.md, "Sun shadows").

usage: python lightingmanifest.py <lightingtable.json> <sdp2spv manifest.json> <replacements/lighting/replace.ini>
"""
import json
import os
import sys

# The game's source file (lower case: the table spells some names differently, e.g. LandO and Lando) -> its GLSL
# rewrite in replacements/lighting, and the defines that file needs for that source (beyond the table's).
SOURCES = {
    'lighting_2x_p_adts_p.hlsl': ('adts.frag', ''),
    'lighting_2x_p_adts10_p.hlsl': ('adts10.frag', ''),
    'lighting_2x_p_lando_p.hlsl': ('lando.frag', ''),
    'lighting_2x_p_land_p.hlsl': ('land.frag', ''),
    'lighting_1x_p_land_p.hlsl': ('land.frag', 'SM1X'),
    'lighting_2x_p_landlighting_p.hlsl': ('landlighting.frag', ''),
    'lighting_2x_p_landlod_p.hlsl': ('landlod.frag', ''),
    'lighting_2x_p_specular_p.hlsl': ('specular.frag', ''),
    'lighting_2x_p_ad_p.hlsl': ('ad.frag', ''),
    'lighting_2x_p_diffusept_p.hlsl': ('diffusept.frag', ''),
    'lighting_2x_p_envmap_p.hlsl': ('envmap.frag', ''),
    'lighting_2x_p_texture_p.hlsl': ('texture.frag', ''),
    'lighting_1x_p_ambdiffdirtexture_p.hlsl': ('x1_ambdiffdirtexture.frag', ''),
    'lighting_1x_p_base_p.hlsl': ('x1_base.frag', ''),
    'lighting_1x_p_si_p.hlsl': ('x1_si.frag', ''),
    'lighting_1x_p_diffusept_p.hlsl': ('x1_light.frag', 'DIFFUSE_PT'),
    'lighting_1x_p_diffusedir_p.hlsl': ('x1_light.frag', 'DIFFUSE_DIR'),
    'lighting_1x_p_specularpt_p.hlsl': ('x1_light.frag', 'SPECULAR_PT'),
    'lighting_1x_p_speculardir_p.hlsl': ('x1_light.frag', 'SPECULAR_DIR'),
    'lighting_1x_p_ambdiffdirandpt_p.hlsl': ('x1_light.frag', 'AMB_DIFF_DIR_AND_PT'),
    'lighting_1x_p_vertdir_p.hlsl': ('x1_vertdir.frag', ''),
    'lighting_1x_p_vertdirandpt_p.hlsl': ('x1_vertdir.frag', 'AND_PT'),
    'lighting_1x_p_envmap_p.hlsl': ('x1_envmap.frag', ''),
    'lighting_1x_p_texeffect_p.hlsl': ('x1_texeffect.frag', ''),
    'tallgrass_1x_p_highdetail_p.hlsl': ('grass.frag', ''),
    'tallgrass_1x_p_highdetail_1pt_p.hlsl': ('grass.frag', 'PT'),
    'speedtree_leaf_p.hlsl': ('leaf.frag', ''),
    'speedtree_frond_p.hlsl': ('frond.frag', ''),
}

# Rows that are not lighting and keep the translated originals: the grass shadow-map pass (TallGrassShader rows with
# SHADOWMAP, GRASS2004..2006).
SKIP_DEFINES = {'SHADOWMAP'}


def rewritten(row):
    return row['source'].lower() in SOURCES and not SKIP_DEFINES & set(row['defines'])

HEADER = """; The game's lighting shaders (ShadowLightShader and the parallax, skin, SpeedTree and grass shaders) rewritten as GLSL
; from their permutation tables (the decomp and tools/ida_shadertables.py; tools/lightingtable.py) and verified against
; the originals on D3D9 (tools/replacediff.py). Generated by tools/lightingmanifest.py: each [Shader.NAME] is the GLSL
; rewrite of the source file that shader was compiled from, with its defines.
[Replacement]
Name=Lighting
Description=The game's lighting as GLSL: the original shading, or physically based shading of the same lights and materials.
Packages={packages}

[Param.pbr]
Label=Physically based lighting
Type=bool
Default=0

[Param.specular]
Label=Specular strength (materials with the game's specular flag)
Type=float
Default=1
Min=0
Max=2

[Param.wet]
Label=Wet world: rain wetness, puddles and ripples (physically based lighting)
Type=bool
Default=1

[Param.puddles]
Label=Wet world: puddles (how much of the rain stands: local puddles' coverage and the water the basins take in)
Type=float
Default=1
Min=0
Max=3
"""


def main():
    doc = json.load(open(sys.argv[1]))
    table = doc['shaders']
    pkg = '%03d' % doc['package']
    sunlit = set()
    builds = {}  # (package, name) -> hash
    for h, s in json.load(open(sys.argv[2], encoding='utf-8'))['shaders'].items():
        for full in s['names']:
            builds[tuple(full.split('/'))] = h
        if s.get('sunLight', -1) >= 0:
            sunlit.update(n.split('/')[1] for n in s['names'] if n.startswith(pkg + '/'))
    replaced = [nm for nm, row in table.items() if rewritten(row)]
    packages = sorted({p for p, _ in builds})
    # A package qualifies when each replaced shader it holds is the verified build (one it lacks is not replaced there).
    same = [p for p in packages if all(builds.get((p, nm)) in (None, builds.get((pkg, nm))) for nm in replaced)]
    out = [HEADER.replace('{packages}', ','.join(same))]
    n = 0
    for name, row in sorted(table.items()):
        if not rewritten(row):
            continue
        src, extra = SOURCES[row['source'].lower()]
        # A value computed at run time (tools/ida_shadertables.py writes it as <expression>, e.g. SPECMULT from a float)
        # is left out: the rewrites reproduce the shipped builds, which do not depend on it.
        defines = ' '.join([k if v == '' else '%s=%s' % (k, v) for k, v in row['defines'].items() if not v.startswith('<')]
                           + extra.split())
        if name in sunlit:
            defines = (defines + ' FNV_SUN').strip()
        # The environment (docs/INDIRECT.md): in the sources whose pbr mode reads it; the object shaders also take the
        # tangent-to-world frame of their vertex shaders.
        text = open(os.path.join(os.path.dirname(sys.argv[3]), src), encoding='utf-8').read()
        if 'pbrAmbient(' in text or 'fnvEnv' in text:
            defines = (defines + ' FNV_ENV').strip()
        if 'fnvAmbientOcclusion(' in text:
            defines = (defines + ' FNV_AO').strip()
        if 'fnvWorldNormal(' in text or 'fnvToWorld(' in text:
            defines = (defines + ' FNV_FRAME').strip()
        # Wet world (docs/WETWORLD.md): the sources whose pbr mode reads the wet block.
        if 'fnvWetness(' in text or 'fnvWetObject' in text:
            defines = (defines + ' FNV_WET').strip()
        # Skin (docs/SKIN.md): the skin builds of the sources with the physically based skin.
        if 'fnvSkinLight(' in text and 'FACEGENBLEND' in defines.split():
            defines = (defines + ' FNV_SKIN').strip()
        out.append('[Shader.%s]\nSource=%s\n%s' % (name, src, 'Defines=%s\n' % defines if defines else ''))
        n += 1
    with open(sys.argv[3], 'w', newline='\n') as f:
        f.write('\n'.join(out))
    print('%d shaders, %d with the sun shadow term; packages with the verified builds: %s' %
          (n, sum(1 for nm in replaced if nm in sunlit), ','.join(same)))


if __name__ == '__main__':
    main()
