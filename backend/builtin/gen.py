"""Regenerates builtin_spv.h from the built-in GLSL shaders with the Vulkan SDK's glslc. usage: python gen.py"""
import os, struct, subprocess, sys
here = os.path.dirname(os.path.abspath(__file__))
glslc = os.path.join(os.environ['VULKAN_SDK'], 'Bin', 'glslc.exe')
out = ['// Generated by backend/builtin/gen.py from the GLSL sources in backend/builtin. Do not edit.', '#pragma once',
       '#include <cstdint>', 'namespace fnvvk::builtin {']
# (array name, source, extra glslc arguments)
shaders = (
    ('kQuadVert', 'quad.vert', []),
    ('kQuadFrag', 'quad.frag', []),
    ('kGammaFrag', 'gamma.frag', []),
    ('kHdrFrag', 'hdr.frag', []),  # HDR10 / scRGB present encode
    ('kShadowVert', 'shadow.vert', []),  # sun shadow casters (backend_shadow.inl)
    ('kShadowAlphaVert', 'shadow.vert', ['-DALPHA']),
    ('kShadowFrag', 'shadow.frag', []),
    ('kFullscreenVert', 'fullscreen.vert', []),
    ('kFsrDepthComp', 'fsrdepth.comp', []),  # FSR 3.1: the world's depth before the first-person view (backend_ffx.inl)
    ('kFsrInputsComp', 'fsrinputs.comp', []),  # FSR 3.1: depth and motion vectors
    ('kPrefilterFrag', 'prefilter.frag', []),  # GGX prefiltering of the environment cube (backend_env.inl)  # the vertex stage of every effect pass (effects are data: effects/)
)
for name, src, extra in shaders:
    spv = os.path.join(here, name + '.spv')
    subprocess.check_call([glslc, '-O', '--target-env=vulkan1.3', *extra, os.path.join(here, src), '-o', spv])
    data = open(spv, 'rb').read()
    os.remove(spv)
    words = struct.unpack('<%dI' % (len(data) // 4), data)
    out.append('inline constexpr uint32_t %s[] = {' % name)
    for i in range(0, len(words), 8):
        out.append('  ' + ', '.join('0x%08Xu' % w for w in words[i:i + 8]) + ',')
    out.append('};')
out.append('}  // namespace fnvvk::builtin')
open(os.path.join(here, '..', 'builtin_spv.h'), 'w').write('\n'.join(out) + '\n')
print('ok')
